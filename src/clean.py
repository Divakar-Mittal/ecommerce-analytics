"""
Clean the raw CSV exports and load them into a SQLite warehouse.

Every rule that removes or changes data is logged, and the log is written to
reports/data_quality.md so the cleaning is auditable.

Usage:  python -m src.clean
"""
from __future__ import annotations

import sqlite3
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
RAW_DIR = ROOT / "data" / "raw"
DB_PATH = ROOT / "data" / "processed" / "warehouse.db"
DQ_REPORT = ROOT / "reports" / "data_quality.md"

VALID_STATUSES = {"delivered", "returned", "cancelled"}


class CleaningLog:
    def __init__(self) -> None:
        self.rows: list[tuple[str, str, int]] = []

    def add(self, table: str, rule: str, affected: int) -> None:
        self.rows.append((table, rule, int(affected)))

    def to_markdown(self, before: dict[str, int], after: dict[str, int]) -> str:
        out = ["# Data Quality Report", "", "Generated by `src/clean.py`.", "",
               "## Row counts", "", "| Table | Raw rows | Clean rows | Removed |", "|---|---:|---:|---:|"]
        for t in before:
            out.append(f"| {t} | {before[t]:,} | {after[t]:,} | {before[t] - after[t]:,} |")
        out += ["", "## Rules applied", "", "| Table | Rule | Rows affected |", "|---|---|---:|"]
        out += [f"| {t} | {r} | {n:,} |" for t, r, n in self.rows]
        return "\n".join(out) + "\n"


# ---------------------------------------------------------------- helpers
def normalize_text(s: pd.Series) -> pd.Series:
    """' north ', 'NORTH', 'north' -> 'North'; 'paid search' -> 'Paid Search'."""
    return s.astype("string").str.strip().str.replace(r"\s+", " ", regex=True).str.title()


def parse_mixed_dates(s: pd.Series) -> pd.Series:
    """Parse a column that mixes ISO (2025-03-01) and day-first (01/03/2025) dates."""
    s = s.astype("string").str.strip()
    iso = pd.to_datetime(s, format="%Y-%m-%d", errors="coerce")
    dayfirst = pd.to_datetime(s, format="%d/%m/%Y", errors="coerce")
    return iso.fillna(dayfirst)


def parse_price(s: pd.Series) -> pd.Series:
    """'$1,234.50' -> 1234.5 ; numbers pass through ; junk -> NaN."""
    cleaned = s.astype("string").str.replace(r"[$,\s]", "", regex=True)
    return pd.to_numeric(cleaned, errors="coerce").astype("float64")


# ---------------------------------------------------------------- tables
def clean_products(df: pd.DataFrame, log: CleaningLog) -> pd.DataFrame:
    df = df.drop_duplicates("product_id").copy()
    df["category"] = df["category"].str.strip()
    df["gross_margin_pct"] = ((df["list_price"] - df["unit_cost"]) / df["list_price"]).round(4)
    return df


def clean_customers(df: pd.DataFrame, log: CleaningLog) -> pd.DataFrame:
    n = len(df)
    df = df.drop_duplicates()
    log.add("customers", "Exact duplicate rows removed", n - len(df))
    n = len(df)
    df = df.drop_duplicates("customer_id", keep="first").copy()
    log.add("customers", "Duplicate customer_id removed", n - len(df))

    for col in ["region", "acquisition_channel"]:
        before = df[col].copy()
        df[col] = normalize_text(df[col])
        log.add("customers", f"`{col}` casing/whitespace standardised", (before != df[col]).sum())

    bad_age = ~df["age"].between(16, 100) & df["age"].notna()
    log.add("customers", "Impossible ages (outside 16-100) set to NULL", bad_age.sum())
    df.loc[bad_age, "age"] = np.nan
    log.add("customers", "Missing age (kept, left NULL)", df["age"].isna().sum())
    df["age"] = df["age"].astype("Int64")
    df["signup_date"] = parse_mixed_dates(df["signup_date"])
    df["age_band"] = pd.cut(df["age"].astype("float"), [15, 24, 34, 44, 54, 100],
                            labels=["18-24", "25-34", "35-44", "45-54", "55+"]).astype("string")
    return df


def clean_orders(df: pd.DataFrame, valid_customers: set[int], log: CleaningLog) -> pd.DataFrame:
    n = len(df)
    df = df.drop_duplicates()
    log.add("orders", "Exact duplicate rows removed", n - len(df))
    n = len(df)
    df = df.drop_duplicates("order_id", keep="first").copy()
    log.add("orders", "Duplicate order_id removed", n - len(df))

    raw_dates = df["order_date"].astype("string")
    df["order_date"] = parse_mixed_dates(raw_dates)
    log.add("orders", "Day-first dates (DD/MM/YYYY) converted to ISO", raw_dates.str.contains("/", na=False).sum())
    bad_date = df["order_date"].isna()
    log.add("orders", "Unparseable order_date removed", bad_date.sum())
    df = df[~bad_date]

    before = df["status"].copy()
    df["status"] = df["status"].astype("string").str.strip().str.lower()
    log.add("orders", "`status` casing standardised", (before != df["status"]).sum())
    bad_status = ~df["status"].isin(VALID_STATUSES)
    log.add("orders", "Unknown status removed", bad_status.sum())
    df = df[~bad_status]

    test = df["discount_code"].astype("string").str.upper().eq("TEST").fillna(False).astype(bool)
    orphan = ~df["customer_id"].isin(valid_customers)
    log.add("orders", "Test orders / orders for unknown customers removed", (test | orphan).sum())
    df = df[~(test | orphan)].copy()

    df["discount_code"] = df["discount_code"].fillna("").astype("string").str.strip().str.upper()
    df["has_discount"] = df["discount_code"].ne("")
    return df


def clean_items(df: pd.DataFrame, valid_orders: set[int], valid_products: set[int], log: CleaningLog) -> pd.DataFrame:
    n = len(df)
    df = df.drop_duplicates().copy()
    log.add("order_items", "Exact duplicate rows removed", n - len(df))

    text_price = df["unit_price"].astype("string").str.contains(r"\$", na=False)
    df["unit_price"] = parse_price(df["unit_price"])
    log.add("order_items", "Prices stored as text ('$1,234.00') converted to numbers", text_price.sum())

    bad_qty = df["quantity"] <= 0
    log.add("order_items", "Non-positive quantity removed", bad_qty.sum())
    no_product = df["product_id"].isna() | ~df["product_id"].isin(valid_products)
    log.add("order_items", "Missing / unknown product_id removed", no_product.sum())
    no_order = ~df["order_id"].isin(valid_orders)
    log.add("order_items", "Items belonging to removed orders dropped", (no_order & ~bad_qty & ~no_product).sum())
    bad_price = df["unit_price"].isna() | (df["unit_price"] <= 0)
    log.add("order_items", "Missing / non-positive price removed", bad_price.sum())

    df = df[~(bad_qty | no_product | no_order | bad_price)].copy()
    df["product_id"] = df["product_id"].astype(int)
    df["line_total"] = (df["quantity"] * df["unit_price"]).round(2)
    return df


# ---------------------------------------------------------------- pipeline
def run(raw_dir: Path = RAW_DIR, db_path: Path = DB_PATH, report_path: Path = DQ_REPORT) -> dict[str, pd.DataFrame]:
    log = CleaningLog()
    raw = {
        "products": pd.read_csv(raw_dir / "products.csv"),
        "customers": pd.read_csv(raw_dir / "customers.csv"),
        "orders": pd.read_csv(raw_dir / "orders.csv", dtype={"discount_code": "string"}),
        "order_items": pd.read_csv(raw_dir / "order_items.csv", dtype={"unit_price": "string", "product_id": "Int64"}),
    }

    products = clean_products(raw["products"], log)
    customers = clean_customers(raw["customers"], log)
    orders = clean_orders(raw["orders"], set(customers["customer_id"]), log)
    items = clean_items(raw["order_items"], set(orders["order_id"]), set(products["product_id"]), log)

    # orders with no surviving items carry no revenue -> drop them too
    empty = ~orders["order_id"].isin(items["order_id"])
    log.add("orders", "Orders left with no valid items removed", empty.sum())
    orders = orders[~empty]

    clean = {"products": products, "customers": customers, "orders": orders, "order_items": items}

    db_path.parent.mkdir(parents=True, exist_ok=True)
    with sqlite3.connect(db_path) as con:
        for name, df in clean.items():
            out = df.copy()
            for col in out.select_dtypes(include=["datetime"]).columns:
                out[col] = out[col].dt.strftime("%Y-%m-%d")
            out.to_sql(name, con, if_exists="replace", index=False)
        con.executescript((ROOT / "sql" / "00_views.sql").read_text())

    report_path.parent.mkdir(parents=True, exist_ok=True)
    report_path.write_text(log.to_markdown({k: len(v) for k, v in raw.items()}, {k: len(v) for k, v in clean.items()}))
    print(f"Warehouse written to {db_path}")
    print(f"Data quality report written to {report_path}")
    return clean


if __name__ == "__main__":
    run()
